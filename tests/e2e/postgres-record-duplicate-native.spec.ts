import { test as base, expect } from '@playwright/test';
import { Client } from 'pg';
import { writeFile } from 'node:fs/promises';
import { postgresRecordDuplicateZh as text } from '../../src/renderer/locales/postgresRecordDuplicate.zh-CN';
import { postgresTableZh as tableText } from '../../src/renderer/locales/postgresTable.zh-CN';
import { postgresRecordViewZh as viewText } from '../../src/renderer/locales/postgresRecordView.zh-CN';
import { postgresBatchDuplicateZh as batchText } from '../../src/renderer/locales/postgresBatchDuplicate.zh-CN';
import { postgresBatchEditZh as editText } from '../../src/renderer/locales/postgresBatchEdit.zh-CN';
import { recordTemplatesZh as templateText } from '../../src/renderer/locales/recordTemplates.zh-CN';
import { draftHistoryZh as historyText } from '../../src/renderer/locales/draftHistory.zh-CN';
import { zh } from '../../src/renderer/locales/zh-CN';
import { navigationMenuItem } from './navigation-menu';

type Runtime = typeof import('./desktop-fixture');
const enabled = !process.argv.includes('--list') && process.env.DBARK_POSTGRES_RECORD_DUPLICATE_NATIVE === '1';
const test: typeof base = enabled ? (require('./desktop-fixture') as Runtime).test : base;
test.skip(!enabled, '仅使用本轮隔离 PostgreSQL 实库');
test.use({ trace: 'off', video: 'off', screenshot: 'off', ...(enabled ? { preserveOnUnconfirmedExit: true } : {}) });
test.describe.configure({ timeout: 120000, retries: 0 });

test('PostgreSQL 复制记录、回滚修正、记录模板和跨页草稿历史', async ({}, info) => {
  const runtime = require('./desktop-fixture') as Runtime;
  const { page, application } = runtime.ownedDesktopResources(info);
  const directory = runtime.dataDir, pid = application.process().pid;
  const observations: string[] = [];
  const mark = async (value: string) => {
    observations.push(value);
    await writeFile(info.outputPath('原生验收.json'), JSON.stringify({ platform: process.platform, pid, directory, observations }, null, 2));
  };
  const check = () => {
    const owner = runtime.ownedDesktopResources(info);
    if (owner.page !== page || owner.application !== application || owner.closed || runtime.dataDir !== directory ||
      info.config.workers !== 1 || info.timeout !== 120000 || info.retry !== 0) throw Error('原生测试归属或门槛已变化');
  };
  const database = process.env.DBARK_POSTGRES_TEST_DATABASE ?? '', user = process.env.DBARK_POSTGRES_TEST_USER;
  const password = process.env.DBARK_POSTGRES_TEST_PASSWORD ?? '', port = Number(process.env.DBARK_POSTGRES_TEST_PORT);
  let reader: Client | undefined;
  try {
    check();
    if (!['darwin', 'win32'].includes(process.platform) || process.env.DBARK_INTEGRATION_ENABLED !== '1' ||
      !/^tabrelio_pg_[a-f0-9]{12}$/.test(database) || user !== database || !/^[a-f0-9]{64}$/.test(password) ||
      !Number.isInteger(port) || port <= 1024 || port > 65535) throw Error('只允许本轮专用角色及 SSH 回环实库');
    reader = new Client({ host: '127.0.0.1', port, database, user, password, ssl: false, connectionTimeoutMillis: 1500 });
    await reader.connect();
    await reader.query(`CREATE TABLE "回归"."复制记录" (
      id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 9007199254740993) PRIMARY KEY,
      legacy bigserial, code text UNIQUE, note text CHECK (note <> '拒绝值'), raw bytea,
      tag text GENERATED ALWAYS AS (note || '-生成') STORED);
      INSERT INTO "回归"."复制记录" (code,note,raw) VALUES ('原编号','甲原',decode('00ff','hex'));
      CREATE TABLE "回归"."模板.""记录" (
        id bigint GENERATED ALWAYS AS IDENTITY (START WITH 9007199254740993) PRIMARY KEY,
        legacy bigserial, note text, amount numeric(40,18), raw bytea, nullable_text text DEFAULT '数据库默认',
        fallback text DEFAULT '数据库默认', tag text GENERATED ALWAYS AS (note || '-生成') STORED);
      INSERT INTO "回归"."模板.""记录" (note,amount,raw,nullable_text,fallback)
        VALUES ('模板原行',90071992547409931234.012345678901234567,decode('00ff','hex'),NULL,'原行专用')`);
    const readRows = async () => (await reader!.query(`SELECT id::text, legacy::text, code, note, encode(raw,'hex') AS raw, tag
      FROM "回归"."复制记录" ORDER BY id`)).rows;
    const originals = await readRows();
    await (await navigationMenuItem(page.locator('.navigation-toolbar'), { name: zh.common.newConnection, exact: true }, check)).click();
    const form = page.getByRole('dialog', { name: zh.common.newConnection, exact: true });
    const title = '复制记录隔离连接';
    await form.getByLabel(zh.connections.text006, { exact: true }).fill(title);
    await form.getByRole('combobox').selectOption('postgresql');
    await form.getByLabel(zh.connections.text010, { exact: true }).fill(String(port));
    await form.getByLabel(zh.common.user, { exact: true }).fill(user);
    await form.getByLabel(zh.connections.text011, { exact: true }).fill(password);
    await form.getByLabel(zh.connections.text012, { exact: true }).fill(database);
    await form.getByLabel(zh.connections.text016, { exact: true }).uncheck();
    await form.getByRole('button', { name: zh.connections.text036, exact: true }).click();
    await expect(form).toBeHidden();
    await page.locator('.connection-row').filter({ hasText: title }).locator('.tree-label').click();
    await page.locator('.database-row .tree-label').filter({ hasText: database }).click();
    await page.locator('.object-row').getByRole('button', { name: '"回归"."复制记录"', exact: true }).click();
    const tab = page.locator('.postgres-table-tab:visible'), grid = tab.getByRole('grid');
    const button = (name: string) => tab.getByRole('button', { name, exact: true });
    const draft = tab.getByLabel(tableText.draft, { exact: true });
    const mode = (dialog: ReturnType<typeof page.getByRole>, field: string) => dialog.getByLabel(field + ' ' + tableText.valueMode, { exact: true });
    const value = (dialog: ReturnType<typeof page.getByRole>, field: string) => dialog.getByLabel(field + ' ' + tableText.value, { exact: true });
    await expect(button(text.action)).toBeDisabled();
    await grid.getByRole('gridcell', { name: '甲原', exact: true }).click();
    await button(tableText.edit).click();
    const edit = page.getByRole('dialog', { name: tableText.edit, exact: true });
    await mode(edit, 'note').selectOption('text');
    await value(edit, 'note').fill('复制自草稿');
    await edit.getByRole('button', { name: tableText.stage, exact: true }).click();
    const duplicate = page.getByRole('dialog', { name: text.title, exact: true });
    await button(text.action).click();
    await expect(duplicate).toContainText('id、legacy、tag');
    await expect(mode(duplicate, 'id')).toHaveValue('unchanged');
    await expect(mode(duplicate, 'legacy')).toHaveValue('unchanged');
    await expect(mode(duplicate, 'raw')).toHaveValue('binary');
    await expect(value(duplicate, 'raw')).toHaveValue('00ff');
    await expect(value(duplicate, 'note')).toHaveValue('复制自草稿');
    await duplicate.getByRole('button', { name: tableText.cancel, exact: true }).click();
    await expect(draft).toContainText('note=复制自草稿');
    expect(await readRows()).toEqual(originals);
    await mark('网格复制带入精确原值和已暂存值，取消保留原草稿');

    await button(viewText.view).click();
    await button(text.action).click();
    await expect(value(duplicate, 'note')).toHaveValue('复制自草稿');
    await value(duplicate, 'code').fill('副本编号');
    await page.screenshot({ path: info.outputPath('PostgreSQL复制当前记录.png') });
    await duplicate.getByRole('button', { name: tableText.stage, exact: true }).click();
    await expect(draft).toContainText(tableText.changes(2));
    await draft.getByRole('listitem').filter({ hasText: /^更新/ }).getByRole('button', { name: tableText.undo, exact: true }).click();
    await expect(draft).toContainText(tableText.changes(1));
    await expect(draft).toContainText('code=副本编号');
    expect(await readRows()).toEqual(originals);
    await mark('记录表单复制独立暂存，撤销原更新不改变副本');

    await button(tableText.preview).click();
    const review = page.getByRole('dialog', { name: tableText.preview, exact: true });
    await expect(review).toContainText('INSERT INTO');
    expect(await readRows()).toEqual(originals);
    await review.getByRole('button', { name: tableText.apply, exact: true }).click();
    await expect(tab.getByText(/已确认整批提交/)).toBeVisible();
    expect(await readRows()).toEqual([originals[0], {
      id: '9007199254740994', legacy: '2', code: '副本编号', note: '复制自草稿', raw: '00ff', tag: '复制自草稿-生成',
    }]);
    await mark('明确提交后仅新增副本，独立读回原记录及生成字段');
    const originalPair = await readRows();
    await button(viewText.grid).click();
    for (const code of ['原编号', '副本编号']) await grid.getByRole('row')
      .filter({ has: page.getByRole('gridcell', { name: code, exact: true }) }).getByRole('checkbox').check();
    const batch = page.getByRole('dialog', { name: batchText.title, exact: true });
    const openBatch = () => button(batchText.action).click();
    const choose = (index: number) => batch.getByRole('button', { name: editText.record(index), exact: true }).click();
    await openBatch();
    await value(batch, 'code').fill('取消副本');
    await batch.getByRole('button', { name: tableText.cancel, exact: true }).click();
    await expect(draft).toHaveCount(0);
    expect(await readRows()).toEqual(originalPair);
    await mark('勾选复制取消后零草稿，原记录保持');

    const editCopies = async () => {
      await openBatch();
      await expect(value(batch, 'code')).toHaveValue('原编号');
      await value(batch, 'code').fill('批量甲');
      await choose(2);
      await expect(value(batch, 'code')).toHaveValue('副本编号');
      await value(batch, 'code').fill('批量乙');
      await choose(1);
      await expect(value(batch, 'code')).toHaveValue('批量甲');
    };
    await editCopies();
    await page.screenshot({ path: info.outputPath('PostgreSQL复制勾选记录.png') });
    await batch.getByRole('button', { name: batchText.stage, exact: true }).click();
    await expect(draft).toContainText(tableText.changes(2));
    await draft.getByRole('button', { name: batchText.undo, exact: true }).click();
    await expect(draft).toHaveCount(0);
    await mark('批量副本分别编辑唯一字段，整批暂存和撤销');

    await editCopies();
    await batch.getByRole('button', { name: batchText.stage, exact: true }).click();
    await button(tableText.preview).click();
    expect(await readRows()).toEqual(originalPair);
    await review.getByRole('button', { name: tableText.apply, exact: true }).click();
    await expect(grid.getByRole('gridcell', { name: '批量乙', exact: true })).toBeVisible();
    expect(await readRows()).toEqual([...originalPair,
      { ...originalPair[0], id: '9007199254740995', legacy: '3', code: '批量甲' },
      { ...originalPair[1], id: '9007199254740996', legacy: '4', code: '批量乙' },
    ]);
    await mark('确认后整批仅新增两个副本，独立读回精确主键和原记录');

    const beforeRollback = await readRows();
    await grid.getByRole('gridcell', { name: '批量乙', exact: true }).click();
    await button(tableText.edit).click();
    await mode(edit, 'note').selectOption('text');
    await value(edit, 'note').fill('拒绝值');
    await edit.getByRole('button', { name: tableText.stage, exact: true }).click();
    await button(tableText.preview).click();
    await review.getByRole('button', { name: tableText.apply, exact: true }).click();
    await expect(review).toBeHidden();
    await expect(tab.getByText(/整批已回滚/)).toContainText(tableText.retryAfterRollback);
    await expect(draft).toContainText('note=拒绝值');
    await expect(button(tableText.preview)).toBeEnabled();
    expect(await readRows()).toEqual(beforeRollback);
    await page.screenshot({ path: info.outputPath('PostgreSQL确认回滚后修正草稿.png') });
    await mark('数据库拒绝更新并回滚，原草稿可继续编辑，独立读回零变动');

    await button(tableText.edit).click();
    await expect(value(edit, 'note')).toHaveValue('拒绝值');
    await value(edit, 'note').fill('回滚后修正');
    await edit.getByRole('button', { name: tableText.stage, exact: true }).click();
    await expect(draft).toContainText('note=回滚后修正');
    await button(tableText.preview).click();
    await expect(review).toContainText('UPDATE');
    expect(await readRows()).toEqual(beforeRollback);
    await review.getByRole('button', { name: tableText.apply, exact: true }).click();
    await expect(grid.getByRole('gridcell', { name: '回滚后修正', exact: true })).toBeVisible();
    await expect(draft).toHaveCount(0);
    expect(await readRows()).toEqual([...beforeRollback.slice(0, -1),
      { ...beforeRollback[3], note: '回滚后修正', tag: '回滚后修正-生成' },
    ]);
    await mark('手动修正原草稿并重新预览，明确确认后只更新目标记录');

    const readTemplateRows = async () => (await reader!.query(`SELECT id::text, legacy::text, note, amount::text,
      encode(raw,'hex') AS raw, nullable_text, fallback, tag FROM "回归"."模板.""记录" ORDER BY id`)).rows;
    const templateOriginals = await readTemplateRows();
    await page.locator('.object-row').getByRole('button', { name: '"回归"."模板.""记录"', exact: true }).click();
    await grid.getByRole('gridcell', { name: '模板原行', exact: true }).click();
    await button(tableText.edit).click();
    await mode(edit, 'note').selectOption('text');
    await value(edit, 'note').fill('暂存模板值');
    await mode(edit, 'raw').selectOption('binary');
    await value(edit, 'raw').fill('ff00');
    await mode(edit, 'fallback').selectOption('default');
    await edit.getByRole('button', { name: tableText.stage, exact: true }).click();
    const template = page.getByRole('dialog', { name: templateText.title, exact: true });
    const templateButton = (name: string) => template.getByRole('button', { name, exact: true });
    const templateField = (name: string) => template.getByRole('checkbox', { name: templateText.field(name), exact: true });
    await button(templateText.open).click();
    for (const name of ['id', 'legacy', 'tag']) await expect(templateField(name)).toHaveCount(0);
    await expect(templateField('fallback')).toBeDisabled();
    for (const name of ['note', 'amount', 'raw', 'nullable_text']) {
      await expect(templateField(name)).not.toBeChecked();
      await templateField(name).check();
    }
    const templateName = '批量新增样式';
    await template.getByLabel(templateText.name, { exact: true }).fill(templateName);
    await templateButton(templateText.save).click();
    await expect(template.getByText(templateText.saved, { exact: true })).toBeVisible();
    expect(await readTemplateRows()).toEqual(templateOriginals);
    await mark('按字段保存本机模板，省略标识、序列、生成和暂存 DEFAULT，实库零写入');

    const showSaved = async () => {
      await button(templateText.open).click();
      await template.getByLabel(templateText.list, { exact: true }).selectOption({ label: templateName });
      await templateButton(templateText.preview).click();
      const saved = template.getByRole('region', { name: templateText.preview, exact: true });
      await expect(saved).toContainText('90071992547409931234.012345678901234567');
      await expect(saved).toContainText('暂存模板值');
      await expect(saved).toContainText(templateText.null);
      await expect(saved).toContainText(templateText.binary(2));
    };
    await templateButton(zh.common.close).click();
    await showSaved();
    const copies = template.getByLabel(templateText.copies, { exact: true });
    await copies.fill('100');
    await templateButton(templateText.stage).click();
    await expect(template.getByRole('alert')).toBeVisible();
    await expect(draft).toContainText(tableText.changes(1));
    await copies.fill('2');
    await templateButton(templateText.stage).click();
    await expect(draft).toContainText(tableText.changes(3));
    await draft.getByRole('button', { name: templateText.undo, exact: true }).click();
    await expect(draft).toContainText(tableText.changes(1));
    await expect(draft).toContainText('note=暂存模板值');
    expect(await readTemplateRows()).toEqual(templateOriginals);
    await mark('总草稿超限整批拒绝，成功新增后一步撤销只恢复应用前的草稿');

    await draft.getByRole('listitem').filter({ hasText: /^更新/ }).getByRole('button', { name: tableText.undo, exact: true }).click();
    await button(tableText.refresh).click();
    await showSaved();
    await expect(template.getByText(templateText.noSource, { exact: true })).toBeVisible();
    await copies.fill('2');
    await page.screenshot({ path: info.outputPath('PostgreSQL记录模板.png') });
    await templateButton(templateText.stage).click();
    await expect(draft).toContainText(tableText.changes(2));
    await button(tableText.preview).click();
    await expect(review).toContainText('INSERT INTO');
    expect(await readTemplateRows()).toEqual(templateOriginals);
    await review.getByRole('button', { name: tableText.apply, exact: true }).click();
    await expect(tab.getByText(/已确认整批提交/)).toBeVisible();
    expect(await readTemplateRows()).toEqual([...templateOriginals, ...['9007199254740994', '9007199254740995'].map((id, index) => ({
      ...templateOriginals[0], id, legacy: String(index + 2), note: '暂存模板值', raw: 'ff00', fallback: '数据库默认', tag: '暂存模板值-生成',
    }))]);
    await mark('刷新无选中记录也可生成，明确提交后仅新增两条精确值、NULL 和默认值正确的记录');

    const beforeHistory = await readTemplateRows();
    const history = tab.getByRole('group', { name: historyText.postgresTitle, exact: true });
    const undo = history.getByRole('button', { name: historyText.undo, exact: true });
    const redo = history.getByRole('button', { name: historyText.redo, exact: true });
    await expect(history).toHaveCount(0);
    await tab.getByLabel(tableText.pageSize, { exact: true }).fill('1');
    await button(tableText.refresh).click();
    // 原网格在读完前仍可见，确认新页投影生效后再选中原行。
    await expect(grid.getByRole('gridcell', { name: '暂存模板值', exact: true })).toHaveCount(0);
    await expect(button(tableText.next)).toBeEnabled();
    const stageNote = async (original: string, next: string, verifyHistoryBlocked = false) => {
      await grid.getByRole('gridcell', { name: original, exact: true }).click();
      await button(tableText.edit).click();
      await mode(edit, 'note').selectOption('text');
      await value(edit, 'note').fill(next);
      if (verifyHistoryBlocked) await expect(undo).toBeDisabled();
      await edit.getByRole('button', { name: tableText.stage, exact: true }).click();
    };
    await stageNote('模板原行', '跨页草稿甲');
    await button(tableText.next).click();
    await expect(tab.getByText(tableText.currentPage(2), { exact: true })).toBeVisible();
    await stageNote('暂存模板值', '跨页草稿乙', true);
    await expect(draft).toContainText(tableText.changes(2));
    const gridNote = grid.getByRole('gridcell', { name: '暂存模板值', exact: true });
    const shortcut = process.platform === 'darwin' ? 'Meta' : 'Control';
    await gridNote.press(shortcut + '+z');
    await expect(draft).toContainText('跨页草稿甲');
    await expect(draft).not.toContainText('跨页草稿乙');
    await undo.click();
    await expect(draft).toHaveCount(0);
    expect(await readTemplateRows()).toEqual(beforeHistory);
    await mark('两个原页分别暂存，网格快捷键和按钮连续撤销至空账本，实库原行保持');

    await button(tableText.next).click();
    await expect(tab.getByText(tableText.currentPage(3), { exact: true })).toBeVisible();
    await redo.click();
    await gridNote.press(shortcut + '+Shift+z');
    await expect(draft).toContainText(tableText.changes(2));
    await expect(draft).toContainText('跨页草稿甲');
    await expect(draft).toContainText('跨页草稿乙');
    await page.screenshot({ path: info.outputPath('PostgreSQL跨页草稿历史.png') });
    await button(tableText.preview).click();
    await expect(review).toContainText('UPDATE');
    await expect(undo).toBeDisabled();
    expect(await readTemplateRows()).toEqual(beforeHistory);
    await mark('空账本翻页后仍可重做两个原页，SQL 预览和模态拦截期间实库保持');

    await review.getByRole('button', { name: tableText.apply, exact: true }).click();
    await expect(tab.getByText(/已确认整批提交/)).toBeVisible();
    await expect(history).toHaveCount(0);
    expect(await readTemplateRows()).toEqual([
      { ...beforeHistory[0], note: '跨页草稿甲', tag: '跨页草稿甲-生成' },
      { ...beforeHistory[1], note: '跨页草稿乙', tag: '跨页草稿乙-生成' },
      beforeHistory[2],
    ]);
    await mark('明确提交只更新两个原页目标，第三行保持，提交后清空撤销和重做');

    check();
    expect(runtime.pageErrors).toEqual([]);
    await reader.end();
    reader = undefined;
    await runtime.confirmOwnedDesktopExit(info);
    await mark('窗口正常退出');
  } catch (error) {
    runtime.retainOwnedDesktopResources(info);
    await mark('专项未完成，保留原窗口和工作区');
    throw error;
  } finally { await reader?.end(); }
});
